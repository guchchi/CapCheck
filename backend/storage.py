"""JSON-file scan storage.

One scan per file: data/scans/{scan_id}.json. Writes are atomic so a crash
mid-scan cannot leave a truncated artifact that later breaks the API.
"""

from __future__ import annotations

import json
import os
import uuid
from datetime import datetime, timezone
from pathlib import Path

from backend.config import settings
from backend.models import Scan


def new_scan_id() -> str:
    return "sc_" + uuid.uuid4().hex[:12]


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _path_for(scan_id: str) -> Path:
    # scan ids are generated by us; reject anything that is not a plain id.
    if not scan_id.startswith("sc_") or not scan_id[3:].isalnum():
        raise ValueError("invalid scan id")
    return settings.scans_dir / f"{scan_id}.json"


def save(scan: Scan) -> None:
    settings.scans_dir.mkdir(parents=True, exist_ok=True)
    target = _path_for(scan.id)
    tmp = target.with_suffix(".json.tmp")
    payload = json.dumps(scan.to_dict(), indent=2)
    tmp.write_text(payload, encoding="utf-8")
    os.replace(tmp, target)


def load(scan_id: str) -> Scan | None:
    try:
        target = _path_for(scan_id)
    except ValueError:
        return None
    if not target.is_file():
        return None
    payload = json.loads(target.read_text(encoding="utf-8"))
    return Scan.from_dict(payload)
